import { Inject, Injectable, Optional } from '@nestjs/common';
import { DATABASE_ADAPTER, SecretCipher, type DatabaseAdapter } from '@zucker-framework/core';
import {
  TotpValidator, generateRecoveryCodes, generateTotpCode, generateTotpSecret, hashRecoveryCode, normalizeRecoveryCode, totpProvisioningUri,
} from '@zucker-framework/auth';
import { RUNTIME_ENVIRONMENT } from '../../runtime-settings/runtime-settings.tokens';
import { ACCOUNT_SECURITY_CLOCK, type AccountSecurityClock } from './account-security.clock';
import { ACCOUNT_SECURITY_ERRORS as E, accountSecurityError } from './account-security.errors';

export const TOTP_PERIOD_SECONDS = 30;
/** Accepted clock drift in steps on either side (same as the validator's window). */
export const TOTP_WINDOW = 1;
export const RECOVERY_CODE_COUNT = 10;

/** A second factor typed by the user: a 6-digit authenticator code or one recovery code. */
export type SecondFactor = { code: string } | { recoveryCode: string };
export interface TwoFactorRow {
  userId: string; secretCiphertext: string; status: 'pending' | 'active'; confirmedAt: Date | null; lastUsedStep: number | null;
}
export interface TwoFactorStatus {
  /** Enrolment possible on this server (encryption key configured). Policy is read separately. */
  available: boolean;
  status: 'off' | 'pending' | 'active';
  confirmedAt: string | null;
  recoveryCodesRemaining: number;
}

/** Parses `{code}` or `{recoveryCode}` (exactly one) out of an already key-checked body. */
export function secondFactor(input: Record<string, string>): SecondFactor | null {
  const code = input.code, recovery = input.recoveryCode;
  if ((code === undefined) === (recovery === undefined)) return null;
  if (code !== undefined) return /^\d{6}$/.test(code.trim()) ? { code: code.trim() } : null;
  return normalizeRecoveryCode(recovery) ? { recoveryCode: recovery! } : null;
}

/**
 * TOTP enrolment and verification for template accounts. The secret is generated by the auth package,
 * encrypted with `CONFIG_ENCRYPTION_KEY` (same key rule as connection profiles: at least 32 characters
 * and different from JWT_SECRET) and returned exactly once. Without a key, enrolment and every check of
 * an enrolled account fail closed with 503 `TWO_FACTOR_UNAVAILABLE`; nothing is written.
 *
 * Replay: the validator's per-process guard and lockout (5 wrong codes → 15 minutes) run first, then a
 * conditional update of `lastUsedStep` (`WHERE lastUsedStep IS NULL OR lastUsedStep < step`, affected
 * rows checked) makes a step usable once across every instance. Wrong recovery codes count toward the
 * same lockout; the `two-factor` limiter (ACCOUNT_SECURITY_RATE_LIMITERS) bounds guesses per account. Recovery codes
 * are stored as SHA-256 hashes and spent by a conditional update (`usedAt IS NULL`), so one code
 * succeeds at most once even under concurrent attempts. Callers run `verify` inside the transaction that
 * performs the protected action, so a rolled-back action does not spend the factor.
 */
@Injectable()
export class AccountTwoFactorService {
  private readonly validator: TotpValidator;
  private readonly cipher: SecretCipher | null;
  private readonly issuer: string;

  constructor(@Inject(DATABASE_ADAPTER) private readonly db: DatabaseAdapter,
    @Inject(ACCOUNT_SECURITY_CLOCK) private readonly clock: AccountSecurityClock,
    @Optional() @Inject(RUNTIME_ENVIRONMENT) environment?: Readonly<NodeJS.ProcessEnv>) {
    const env = environment ?? process.env;
    const key = env.CONFIG_ENCRYPTION_KEY;
    this.cipher = key && key.trim().length >= 32 && key !== env.JWT_SECRET ? new SecretCipher({ masterKey: key }) : null;
    this.issuer = issuerName(env);
    this.validator = new TotpValidator({ period: TOTP_PERIOD_SECONDS, window: TOTP_WINDOW, maxAttempts: 5, lockMs: 15 * 60_000,
      now: () => this.clock().getTime() });
  }

  /** Encryption key configured: enrolment and enrolled sign-in can work. */
  available(): boolean { return this.cipher !== null; }
  assertAvailable(): void {
    if (!this.cipher) throw accountSecurityError(503, E.twoFactorUnavailable, 'Two-factor authentication is not configured on this server');
  }

  async row(userId: string, db: DatabaseAdapter = this.db): Promise<TwoFactorRow | null> {
    return await db.model('accountTwoFactor').findUnique({ where: { userId } }) as TwoFactorRow | null;
  }

  async status(userId: string): Promise<TwoFactorStatus> {
    const row = await this.row(userId);
    const remaining = row?.status === 'active' ? await this.db.model('accountRecoveryCodes').count({ where: { userId, usedAt: null } }) : 0;
    return { available: this.available(), status: row?.status ?? 'off', confirmedAt: row?.confirmedAt?.toISOString() ?? null,
      recoveryCodesRemaining: remaining };
  }

  /**
   * Starts (or restarts) an enrolment: a new secret replaces any pending one. Returns the secret and its
   * `otpauth://` URI exactly once. An active enrolment must be disabled first (409).
   */
  async enrol(user: { id: string; username: string; email?: string | null }): Promise<{ secret: string; otpauthUri: string }> {
    this.assertAvailable();
    const secret = generateTotpSecret();
    const otpauthUri = totpProvisioningUri({ secret, account: user.email || user.username, issuer: this.issuer });
    const secretCiphertext = this.cipher!.encrypt(secret);
    await this.db.$transaction(async tx => {
      await this.lockUser(tx, user.id);
      const existing = await this.row(user.id, tx);
      if (existing?.status === 'active') throw accountSecurityError(409, E.twoFactorAlreadyEnabled, 'Two-factor authentication is already on');
      const now = this.clock();
      if (existing) {
        await tx.model('accountTwoFactor').update({ where: { userId: user.id },
          data: { secretCiphertext, status: 'pending', confirmedAt: null, lastUsedStep: null, updatedAt: now } });
      } else {
        await tx.model('accountTwoFactor').create({ data: { userId: user.id, secretCiphertext, status: 'pending', createdAt: now, updatedAt: now } });
      }
    });
    return { secret, otpauthUri };
  }

  /**
   * Confirms a pending enrolment with its first code: the row becomes active, fresh recovery codes are
   * returned once, and `credentialVersion` is bumped so every other session (and outstanding mail
   * tickets) ends; the calling session is carried over to the new version.
   */
  async confirm(userId: string, sessionId: string, code: string): Promise<{ recoveryCodes: string[] }> {
    this.assertAvailable();
    if (typeof code !== 'string' || !/^\d{6}$/.test(code.trim())) throw accountSecurityError(400, E.twoFactorCodeInvalid, 'Invalid code');
    return this.db.$transaction(async tx => {
      await this.lockUser(tx, userId);
      const row = await this.row(userId, tx);
      if (row?.status !== 'pending') throw accountSecurityError(409, E.twoFactorNotPending, 'Start two-factor enrolment first');
      if (!await this.verifyTotp(tx, row, code.trim())) throw accountSecurityError(400, E.twoFactorCodeInvalid, 'Invalid code');
      const now = this.clock();
      await tx.model('accountTwoFactor').update({ where: { userId }, data: { status: 'active', confirmedAt: now, updatedAt: now } });
      const recoveryCodes = await this.replaceRecoveryCodes(tx, userId);
      const user = await tx.model('users').update({ where: { id: userId }, data: { credentialVersion: { increment: 1 } },
        select: { credentialVersion: true } }) as { credentialVersion: number };
      await tx.model('accountSessions').updateMany({ where: { userId, revokedAt: null, id: { not: sessionId } },
        data: { revokedAt: now, revokedReason: 'two-factor-enabled' } });
      await tx.model('accountSessions').updateMany({ where: { id: sessionId, userId, revokedAt: null },
        data: { credentialVersion: user.credentialVersion } });
      return { recoveryCodes };
    });
  }

  /** Turns two-factor off after a valid code or recovery code (the caller checked recent authentication). */
  async disable(userId: string, factor: SecondFactor): Promise<{ success: true }> {
    await this.db.$transaction(async tx => {
      await this.lockUser(tx, userId);
      const row = await this.row(userId, tx);
      if (row?.status !== 'active') throw accountSecurityError(409, E.twoFactorNotEnabled, 'Two-factor authentication is off');
      if (!await this.verify(tx, userId, factor)) throw accountSecurityError(400, E.twoFactorCodeInvalid, 'Invalid code');
      await tx.model('accountRecoveryCodes').deleteMany({ where: { userId } });
      await tx.model('accountTwoFactor').delete({ where: { userId } });
    });
    return { success: true };
  }

  /** Replaces every recovery code after a valid authenticator code; the new set is returned once. */
  async regenerateRecoveryCodes(userId: string, code: string): Promise<{ recoveryCodes: string[] }> {
    return this.db.$transaction(async tx => {
      await this.lockUser(tx, userId);
      const row = await this.row(userId, tx);
      if (row?.status !== 'active') throw accountSecurityError(409, E.twoFactorNotEnabled, 'Two-factor authentication is off');
      if (!await this.verify(tx, userId, { code })) throw accountSecurityError(400, E.twoFactorCodeInvalid, 'Invalid code');
      return { recoveryCodes: await this.replaceRecoveryCodes(tx, userId) };
    });
  }

  /**
   * Back-office reset (lost device): removes the enrolment (pending or active) and every recovery code,
   * bumps `credentialVersion` and ends every session of the account, and writes an `operationLogs` row,
   * all in one transaction. The caller checked the actor's permission and recent authentication.
   * Returns the account's address for the post-commit notice. 404 unknown account, 409 when off.
   */
  async adminReset(actorId: string, userId: string, request: { method: string; path: string; ipAddress?: string }):
    Promise<{ email: string | null; locale: string | null }> {
    return this.db.$transaction(async tx => {
      await this.lockUser(tx, userId);
      const user = await tx.model('users').findUnique({ where: { id: userId }, select: { id: true, email: true, locale: true } }) as
        { id: string; email: string | null; locale: string | null } | null;
      if (!user) throw accountSecurityError(404, E.twoFactorNotEnabled, 'Account not found');
      const row = await this.row(userId, tx);
      if (!row) throw accountSecurityError(409, E.twoFactorNotEnabled, 'Two-factor authentication is off');
      const now = this.clock();
      const removedCodes = await tx.model('accountRecoveryCodes').deleteMany({ where: { userId } });
      await tx.model('accountTwoFactor').delete({ where: { userId } });
      await tx.model('users').update({ where: { id: userId }, data: { credentialVersion: { increment: 1 } } });
      await tx.model('accountSessions').updateMany({ where: { userId, revokedAt: null }, data: { revokedAt: now, revokedReason: 'two-factor-reset' } });
      // Ids and counts only; never secrets, codes or addresses.
      await tx.model('operationLogs').create({ data: { module: 'account-security', action: 'two-factor-reset', status: 'SUCCESS',
        userId: actorId, targetId: userId, targetType: 'user', method: request.method, path: request.path, ipAddress: request.ipAddress ?? null,
        metadata: { previousStatus: row.status, recoveryCodesRemoved: (removedCodes as { count: number }).count } } });
      return { email: user.email, locale: user.locale };
    });
  }

  /**
   * Checks one factor of an **active** enrolment on the caller's transaction. False for anything that
   * should not pass (no active row, wrong/replayed/locked code, unknown or spent recovery code).
   * Throws 503 when the account is enrolled but the server cannot decrypt secrets.
   */
  async verify(tx: DatabaseAdapter, userId: string, factor: SecondFactor): Promise<boolean> {
    const row = await this.row(userId, tx);
    if (row?.status !== 'active') return false;
    this.assertAvailable();
    if ('code' in factor) return typeof factor.code === 'string' && this.verifyTotp(tx, row, factor.code.trim());
    // Recovery codes share the authenticator lockout: a locked account accepts neither factor, and
    // every wrong recovery code counts as a failed attempt (no unlimited guessing of the 10 codes).
    if (await this.validator.isLockedOut(userId)) return false;
    const normalized = normalizeRecoveryCode(factor.recoveryCode);
    const spent = normalized ? await tx.model('accountRecoveryCodes').updateMany({
      where: { userId, codeHash: hashRecoveryCode(normalized), usedAt: null }, data: { usedAt: this.clock() } }) : { count: 0 };
    if (spent.count !== 1) await this.validator.recordFailedAttempt(userId);
    return spent.count === 1;
  }

  private async verifyTotp(tx: DatabaseAdapter, row: TwoFactorRow, code: string): Promise<boolean> {
    if (!/^\d{6}$/.test(code)) return false;
    let secret: string;
    try { secret = this.cipher!.decrypt(row.secretCiphertext); }
    catch { throw accountSecurityError(503, E.twoFactorUnavailable, 'Two-factor secrets cannot be read with the configured key'); }
    if (!await this.validator.verifyOnce(row.userId, code, secret)) return false;
    const step = this.matchedStep(secret, code);
    if (step === null) return false;
    // Cross-instance replay guard: a step (or an older one) is accepted once per enrolment.
    const claimed = await tx.model('accountTwoFactor').updateMany({
      where: { userId: row.userId, status: row.status, OR: [{ lastUsedStep: null }, { lastUsedStep: { lt: step } }] },
      data: { lastUsedStep: step, updatedAt: this.clock() } });
    // Another instance accepted this step first: a replay, counted like any wrong code.
    if (claimed.count !== 1) await this.validator.recordFailedAttempt(row.userId);
    return claimed.count === 1;
  }

  private matchedStep(secret: string, code: string): number | null {
    const now = this.clock().getTime(), current = Math.floor(now / 1000 / TOTP_PERIOD_SECONDS);
    for (let offset = -TOTP_WINDOW; offset <= TOTP_WINDOW; offset++) {
      if (generateTotpCode({ secret, time: (current + offset) * TOTP_PERIOD_SECONDS * 1000, period: TOTP_PERIOD_SECONDS }) === code) return current + offset;
    }
    return null;
  }

  private async replaceRecoveryCodes(tx: DatabaseAdapter, userId: string): Promise<string[]> {
    const codes = generateRecoveryCodes(RECOVERY_CODE_COUNT);
    await tx.model('accountRecoveryCodes').deleteMany({ where: { userId } });
    const now = this.clock();
    for (const code of codes) await tx.model('accountRecoveryCodes').create({ data: { userId, codeHash: hashRecoveryCode(code), createdAt: now } });
    return codes;
  }

  /** Serialises enrolment changes per account (same row lock the OAuth flows use). */
  private async lockUser(tx: DatabaseAdapter, userId: string): Promise<void> {
    const query = (tx as Partial<{ query(sql: string, values: unknown[]): Promise<unknown> }>).query;
    if (typeof query === 'function') await query.call(tx, 'SELECT id FROM users WHERE id = $1 FOR UPDATE', [userId]);
  }
}

/** Issuer label in authenticator apps: `SITE_NAME`, else the `WEB_URL` host, else "Zucker". */
function issuerName(env: Readonly<NodeJS.ProcessEnv>): string {
  const configured = env.SITE_NAME?.replace(/[\u0000-\u001f\u007f:]/g, '').trim().slice(0, 60);
  if (configured) return configured;
  try { return env.WEB_URL ? new URL(env.WEB_URL).host : 'Zucker'; } catch { return 'Zucker'; }
}
