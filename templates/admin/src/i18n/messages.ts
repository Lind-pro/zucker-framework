export type AdminLocale = 'zh' | 'en';
export type AdminMessageParams = Record<string, string | number>;
export function translateAdminText(
  locale: AdminLocale,
  chinese: string,
  english?: string,
  params: AdminMessageParams = {},
): string {
  const own = (messages: Readonly<Record<string, string>>) =>
    Object.prototype.hasOwnProperty.call(messages, chinese) ? messages[chinese] : undefined;
  const message =
    locale === 'zh'
      ? chinese
      : (english ?? own(adminMessages) ?? own(adminPageMessages) ?? chinese);
  return message.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : placeholder,
  );
}
